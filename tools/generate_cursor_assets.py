#!/usr/bin/env python3
"""Embed the bundled SoFPlus cursor for the F12 cursor toggle."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSET = ROOT / "rsrc" / "assets" / "cursor" / "sofplus_cursor.m32"


def write_text_if_changed(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8")


def main() -> int:
    if not ASSET.is_file():
        print(f"missing {ASSET}", file=sys.stderr)
        return 1
    out_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build" / "release"
    data = ASSET.read_bytes()
    if len(data) < 60 or int.from_bytes(data[:4], "little") != 4:
        print(f"invalid cursor m32: {ASSET}", file=sys.stderr)
        return 1
    internal = data[4:60].split(b"\0", 1)[0]
    if internal != b"pics/menus/cursor/cursor":
        print(f"unexpected cursor internal name {internal!r} in {ASSET}", file=sys.stderr)
        return 1
    lines = [
        "/* Auto-generated by tools/generate_cursor_assets.py */",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "static const unsigned char kSofPlusCursorM32[] = {",
    ]
    for pos in range(0, len(data), 20):
        chunk = data[pos : pos + 20]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    lines.extend(
        [
            "};",
            f"static constexpr int kSofPlusCursorM32Size = {len(data)};",
            "",
        ]
    )
    out = out_dir / "cursor_assets.inc"
    write_text_if_changed(out, "\n".join(lines))
    print(f"cursor asset: {len(data)} bytes -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
